--TASK 1
SELECT MANAGER_ID, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE MANAGER_ID IS NOT NULL
GROUP BY MANAGER_ID
ORDER BY ISCI_SAYI DESC;
 
--TASK 2
SELECT COUNTRY_ID, COUNT(*) AS OFIS_SAYI
FROM HR.LOCATIONS
WHERE COUNTRY_ID IS NOT NULL
GROUP BY COUNTRY_ID
ORDER BY OFIS_SAYI DESC;

--TASK 3 
SELECT E.FIRST_NAME, E.LAST_NAME, J.JOB_TITLE
FROM HR.EMPLOYEES E
JOIN HR.JOBS J
ON E.JOB_ID = J.JOB_ID;

--TASK 4
SELECT DEPARTMENT_ID, ROUND(AVG(SALARY),2) AS ORTA_MAAS
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING AVG(SALARY)>8000;

--TASK 5
SELECT DEPARTMENT_ID, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE SALARY >= 3000
GROUP BY DEPARTMENT_ID
HAVING COUNT(*) > 3;

--TASK 6
SELECT J.JOB_TITLE, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES E
JOIN HR.JOBS J 
ON E.JOB_ID = J.JOB_ID 
GROUP BY J.JOB_TITLE
ORDER BY ISCI_SAYI DESC;

--TASK 7
SELECT L.CITY, L.COUNTRY_ID 
FROM HR.LOCATIONS L
LEFT JOIN HR.DEPARTMENTS D 
ON L.LOCATION_ID = D.LOCATION_ID
WHERE D.DEPARTMENT_ID IS NULL;


--TASK 8
-- 1. LAST_NAME EHTIYAC YOXDUR
-- 2. 3'CU SETIRDE J.JOB_ID OLMALIDIR
-- 3. WHERE AQREQAT FUNKSIYALAR ILE ISLEMIR
SELECT J.JOB_TITLE, AVG(E.SALARY) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.JOBS J ON E.JOB_ID = J.JOB_ID
GROUP BY J.JOB_TITLE
HAVING AVG(E.SALARY) > 10000;

-- TASK 9
SELECT L.CITY, COUNT(*) AS ISCI_SAYI, ROUND(AVG(E.SALARY)) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN HR.LOCATIONS L ON D.LOCATION_ID = L.LOCATION_ID
GROUP BY L.CITY
HAVING COUNT(*)>5
ORDER BY ISCI_SAYI DESC;

-- TASK 10
SELECT D.DEPARTMENT_NAME, COUNT(E.EMPLOYEE_ID) AS ISCI_SAYI 
FROM HR.DEPARTMENTS D
LEFT JOIN HR.EMPLOYEES E 
ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_ID, D.DEPARTMENT_NAME
ORDER BY ISCI_SAYI DESC, D.DEPARTMENT_NAME ASC;

--TASK 1
SELECT FIRST_NAME, LAST_NAME, SALARY,
    CASE 
    WHEN SALARY < 6000 THEN 'Asagi'
    WHEN SALARY BETWEEN 6000 AND 12000 THEN 'Orta'
    WHEN SALARY > 12000 THEN 'Yuksek'
    END AS MAAS_SEVIYYESI
FROM HR.EMPLOYEES;

--TASK 2
SELECT FIRST_NAME,JOB_ID,
CASE JOB_ID
    WHEN 'IT_PROG' THEN 'Proqramci'
    WHEN 'SA_REP' THEN 'Satis numayendesi'
    WHEN 'ST_CLERK' THEN 'Anbar iscisi'
    ELSE 'Diger'
    END AS VEZIFE
FROM HR.EMPLOYEES;

--TASK 3
SELECT FIRST_NAME,COMMISSION_PCT,
CASE 
    WHEN COMMISSION_PCT IS NULL THEN 'Komissiya yoxdur'
    ELSE 'Komissiya var'
    END AS KOMISSIYA_STATUSU
FROM HR.EMPLOYEES;

SELECT FIRST_NAME,COMMISSION_PCT,
    NVL2(COMMISSION_PCT, 'Komissiya var', 'Komissiya yoxdur')
    AS KOMISSIYA_STATUSU
FROM HR.EMPLOYEES;

--TASK 4
SELECT CITY,COUNTRY_ID,
CASE 
    WHEN COUNTRY_ID IN('US','CA','MX','BR') THEN 'Amerika'
    WHEN COUNTRY_ID IN('UK','DE','IT','NL','CH') THEN 'Avropa'
    WHEN COUNTRY_ID IN('JP','CN','IN','SG') THEN 'Asiya'
    ELSE 'Diger'
    END AS QITE
FROM HR.LOCATIONS;

--TASK 5
SELECT FIRST_NAME,DEPARTMENT_ID,SALARY,
CASE DEPARTMENT_ID
WHEN 80 THEN SALARY * 0.1
WHEN 60 THEN SALARY * 0.15
ELSE SALARY*0.05
END AS BONUS
FROM HR.EMPLOYEES
ORDER BY BONUS DESC;

--TASK 6
--BIRINCI SALARY>15000 SERTI YAZILMALIDIR
--ELSE 0 EVEZINE ASAGI YAZILMALIDIR, HEMCININ 0 SETIR TIPI DEYIL
--ALIAS DIRNAQSIZ VE YA IKI DIRNAQLA YAZILMALIDIR.
SELECT FIRST_NAME,SALARY,
CASE 
    WHEN SALARY > 15000 THEN 'Yuksek'
    WHEN SALARY > 5000 THEN 'Orta'
    ELSE 'Asagi'
    END AS SEVIYYE
FROM HR.EMPLOYEES;

--TASK 7
SELECT FIRST_NAME,JOB_ID,MANAGER_ID,
CASE 
    WHEN MANAGER_ID IS NULL THEN 'Direktor'
    WHEN MANAGEr_ID = 100 THEN 'Direktorun komandasi'
    WHEN JOB_ID LIKE '%MAN' OR JOB_ID LIKE '%MGR' THEN 'Menecer'
    ELSE 'Isci'
    END AS ROL
FROM HR.EMPLOYEES;

--TASK 8
SELECT FIRST_NAME,SALARY,COMMISSION_PCT,
SALARY * NVL(COMMISSION_PCT,0) * 12 AS ILLIK_KOMISSIYA, SALARY * 12 + SALARY*12*NVL(COMMISSION_PCT,0) AS ILLIK_GELIR
FROM HR.EMPLOYEES
ORDER BY ILLIK_GELIR DESC;

--TASK 9
SELECT E.FIRST_NAME,J.JOB_TITLE,E.SALARY,J.MIN_SALARY,J.MAX_SALARY,
CASE 
    WHEN E.SALARY = J.MIN_SALARY THEN 'Minimumda'
    WHEN E.SALARY = J.MAX_SALARY THEN 'Maksimumda'
    WHEN E.SALARY < (J.MIN_SALARY + J.MAX_SALARY)/2 THEN 'Asagi yarida'
    ELSE 'Yuxari yarida'
    END AS MOVQE
FROM HR.EMPLOYEES E
JOIN HR.JOBS J ON E.JOB_ID = J.JOB_ID;

--TASK 10
SELECT E.FIRST_NAME,E.LAST_NAME,
    NVL(D.DEPARTMENT_NAME,'Sobesiz') AS SOBE,
    CASE
        WHEN D.DEPARTMENT_ID IS NULL THEN 'Melum deyil'
        WHEN L.CITY = 'Seattle' THEN 'Bas ofis'
        ELSE 'Filial'
    END AS OFIS
FROM HR.EMPLOYEES E 
LEFT JOIN HR.DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
LEFT JOIN HR.LOCATIONS L ON D.LOCATION_ID = L.LOCATION_ID;
