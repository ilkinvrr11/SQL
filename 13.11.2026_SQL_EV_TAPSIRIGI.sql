--TASK 1 
SELECT E.FIRST_NAME, E.LAST_NAME, 
M.FIRST_NAME AS MENECER_ADI, M.LAST_NAME AS MENECER_SOYADI
FROM HR.EMPLOYEES E 
JOIN HR.EMPLOYEES M ON E.MANAGER_ID = M.EMPLOYEE_ID;

--TASK 2
SELECT E.FIRST_NAME, E.LAST_NAME,
M.FIRST_NAME AS MENECER_ADI, M.LAST_NAME AS MENECER_SOYADI
FROM HR.EMPLOYEES E 
LEFT JOIN HR.EMPLOYEES M ON E.MANAGER_ID = M.EMPLOYEE_ID;

--TASK 3
SELECT FIRST_NAME, LAST_NAME, DEPARTMENT_ID
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (SELECT DEPARTMENT_ID FROM HR.DEPARTMENTS
WHERE LOCATION_ID = 1700);

--TASK 4
SELECT E.FIRST_NAME,E.LAST_NAME
FROM HR.EMPLOYEES E 
JOIN HR.EMPLOYEES M
ON E.MANAGER_ID = M.EMPLOYEE_ID
WHERE M.FIRST_NAME LIKE 'Steven' AND M.LAST_NAME LIKE 'King';

--TASK 5
SELECT E.FIRST_NAME,E.LAST_NAME,E.SALARY,
M.FIRST_NAME AS MENECER_ADI,M.SALARY AS MENECER_MAASI
FROM HR.EMPLOYEES E 
JOIN HR.EMPLOYEES M ON E.MANAGER_ID=M.EMPLOYEE_ID 
WHERE E.SALARY>M.SALARY;

--TASK 6
SELECT E.FIRST_NAME, E.LAST_NAME,E.DEPARTMENT_ID, 
M.FIRST_NAME AS MENECER_ADI, M.DEPARTMENT_ID AS MENECER_SOBESI
FROM HR.EMPLOYEES E
JOIN HR.EMPLOYEES M ON E.MANAGER_ID = M.EMPLOYEE_ID
WHERE E.DEPARTMENT_ID != M.DEPARTMENT_ID;


--TASK 7
SELECT FIRST_NAME,LAST_NAME,JOB_ID,SALARY 
FROM HR.EMPLOYEES
WHERE JOB_ID IN (SELECT JOB_ID FROM HR.JOBS 
            WHERE MIN_SALARY>=10000);

--TASK 8 
-- SUBQUERY icinde yalniz bir value olmalidir
-- = evezine IN isledilmelidir.
--Sales yazilmalidir.
SELECT FIRST_NAME, LAST_NAME
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (SELECT DEPARTMENT_ID
                       FROM HR.DEPARTMENTS
                       WHERE DEPARTMENT_NAME IN ('Sales', 'IT'));

--TASK 9
-- 1. 
SELECT FIRST_NAME,LAST_NAME,EMPLOYEE_ID
FROM HR.EMPLOYEES 
WHERE EMPLOYEE_ID IN (SELECT MANAGER_ID FROM HR.EMPLOYEES);
-- 2.
SELECT DISTINCT M.FIRST_NAME, M.LAST_NAME, M.EMPLOYEE_ID
FROM HR.EMPLOYEES E
JOIN HR.EMPLOYEES M ON E.MANAGER_ID = M.EMPLOYEE_ID;
-- SELF JOIN'DE DUPLICATE CIXDIGINA GORE ARADAN QALDIRMAQ UCUN DISTINCT ISTIFADE OLUNDU

--TASK 10
SELECT M.FIRST_NAME AS MENECER_ADI,M.LAST_NAME AS MENECER_SOYADI, COUNT(E.EMPLOYEE_ID) AS TABE_SAYI,
ROUND(AVG(E.SALARY)) AS TABELERIN_ORTA_MAASI 
FROM HR.EMPLOYEES E
JOIN HR.EMPLOYEES M ON E.MANAGER_ID = M.EMPLOYEE_ID
GROUP BY M.FIRST_NAME,M.LAST_NAME,M.EMPLOYEE_ID
HAVING COUNT(E.EMPLOYEE_ID)>5
ORDER BY TABE_SAYI DESC;
